#!/usr/bin/env bash
# Classify all single-arm RLBench tasks by horizon, write docs/RLBENCH_TASK_HORIZON.md, sample K
# short single-skill tasks (seed), generate 1 episode each and run the perception phase split.
#   bash scripts/run_short_task_perception.sh 5 42
set -uo pipefail
K=${1:-5}; SEED=${2:-42}
SIM_PY=${SIM_PY:-$HOME/anaconda3/envs/peract2/bin/python}
export COPPELIASIM_ROOT=${COPPELIASIM_ROOT:-$HOME/CoppeliaSim_Edu_V4_1_0_Ubuntu20_04}
export LD_LIBRARY_PATH=${LD_LIBRARY_PATH:-}:$COPPELIASIM_ROOT
export QT_QPA_PLATFORM_PLUGIN_PATH=$COPPELIASIM_ROOT

echo "== classify tasks"
"$SIM_PY" scripts/classify_rlbench_tasks.py --out docs/rlbench_task_horizon.json || exit 1

TASKS=$(python3 - "$K" "$SEED" <<'PY'
import json, random, sys
k, seed = int(sys.argv[1]), int(sys.argv[2])
d = json.load(open("docs/rlbench_task_horizon.json"))
rows = d["tasks"]
by = {c: [r for r in rows if r["class"] == c] for c in ("short_single", "medium", "long_horizon", "unknown")}
L = ["# RLBench single-arm tasks by demo horizon", "",
     "Generated by `scripts/classify_rlbench_tasks.py` from the pinned fork (`ext/RLBench`). For each task the",
     "scene model's scripted waypoints (`waypoint0..N`) were counted, with grasps (`close_gripper()` in a",
     "waypoint extension) and whether the task re-runs its waypoints (`register_waypoints_should_repeat`). No demo",
     "was executed. Waypoints added in code at runtime are not counted.", "",
     "Criteria (thresholds are a choice):",
     f"- **short single-skill**: {d['criteria']['short_single']};",
     f"- **long-horizon**: {d['criteria']['long_horizon']};",
     "- **medium**: everything else.", "",
     "Grasp counts include closing the gripper before pushing (e.g. `push_button`).", ""]
for c, title in (("short_single", "Short single-skill"), ("medium", "Medium"), ("long_horizon", "Long-horizon"),
                 ("unknown", "Could not load")):
    if not by[c]:
        continue
    L += [f"## {title}: {len(by[c])}", "", "| Task | Waypoints | Grasps | Repeats |", "|---|---|---|---|"]
    L += [f"| `{r['task']}` | {r['waypoints']} | {r['grasps']} | {'yes' if r['repeats'] else ''} |" for r in by[c]]
    L.append("")
open("docs/RLBENCH_TASK_HORIZON.md", "w").write("\n".join(L))
pick = random.Random(seed).sample(sorted(r["task"] for r in by["short_single"]), k)
print(" ".join(pick))
PY
)
echo "== sampled short tasks (seed $SEED): $TASKS"
OUT_ROOT=${OUT_ROOT:-data/entry_process/rlbench_short${K}_seed${SEED}} TASKS="$TASKS" \
  bash scripts/run_rlbench_random_tasks.sh "$K" "$SEED"
